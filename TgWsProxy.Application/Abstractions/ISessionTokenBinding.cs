#nullable enable

namespace TgWsProxy.Application.Abstractions;

/// <summary>
/// Привязка живой сессии к токену доступа прокси (F-8.4, F-8.6). Обработчик сессии сообщает
/// сюда, каким секретом клиент прошёл рукопожатие: без этого отзыв токена не смог бы разорвать
/// именно его соединения, а статистика трафика — отнести байты нужному токену.
/// </summary>
public interface ISessionTokenBinding
{
    /// <summary>
    /// Текущая привязка сессии к токену: <see langword="null"/>, пока рукопожатие не выбрало токен.
    /// Нужна владельцу соединения, чтобы закрыть учёт трафика по той же паре (IP, токен) (F-9.2).
    /// </summary>
    string? TokenId { get; }

    /// <summary>
    /// Запоминает токен, которым прошло рукопожатие. До успешного рукопожатия принадлежность
    /// соединения токену неизвестна, поэтому передаётся <see langword="null"/>.
    /// </summary>
    /// <param name="tokenId">Идентификатор токена или <see langword="null"/>.</param>
    void AssignToken(string? tokenId);
}
