namespace TgWsProxy.Domain;

/// <summary>
/// Снимок токенов доступа прокси, который читает обработчик сессии (F-8.4). Список уже
/// упорядочен так, как требует рукопожатие: сначала токен с самым поздним
/// <see cref="ProxyTokenEntry.LastUsedAt"/>, затем по времени создания.
///
/// Снимок перестраивается лениво и только при изменении конфигурации: рукопожатие выполняется
/// на каждое входящее соединение, и брать блокировку на этом пути нельзя.
/// </summary>
public interface IProxyTokenRegistry
{
    /// <summary>
    /// Включённые токены в порядке перебора для рукопожатия (F-8.4). Пустой список означает,
    /// что ни одно рукопожатие не может быть принято.
    /// </summary>
    IReadOnlyList<ProxyTokenEntry> HandshakeOrder { get; }

    /// <summary>Все токены снимка, включая выключенные (для диагностики и панели).</summary>
    IReadOnlyList<ProxyTokenEntry> All { get; }

    /// <summary>Число включённых токенов (F-8.11).</summary>
    int EnabledCount { get; }

    /// <summary>Находит токен снимка по идентификатору.</summary>
    /// <param name="id">Идентификатор токена (из проверенного Fake TLS ClientHello).</param>
    ProxyTokenEntry? Find(string id);

    /// <summary>
    /// Отмечает успешное использование токена: обновляет <c>lastUsedAt</c> и в снимке, и в
    /// конфигурации, чтобы следующее рукопожатие начиналось с этого токена (F-8.4).
    /// </summary>
    /// <param name="tokenId">Идентификатор токена, прошедшего рукопожатие.</param>
    void Touch(string tokenId);

    /// <summary>
    /// Помечает снимок устаревшим. Вызывается после применения новой конфигурации (§ 2.8, F-8.9):
    /// изменения токенов должны влиять на следующие рукопожатия без перезапуска слушателя.
    /// </summary>
    void Reload();
}
