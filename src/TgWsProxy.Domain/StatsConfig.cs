namespace TgWsProxy.Domain;

/// <summary>
/// Статистика по источникам трафика — пары «IP + токен» (вложенный блок <c>stats</c>, F-4).
/// Все ключи блока — «горячо»: применяются к работающему реестру без перезапуска слушателя.
/// </summary>
public sealed class StatsConfig
{
    /// <summary>
    /// Включает учёт статистики по каждому IP-адресу (требование F-4). Выключение экономит
    /// память: <c>/api/per-ip</c> вернёт пустой список.
    /// </summary>
    public bool Enabled { get; set; } = true;

    /// <summary>
    /// Время жизни записи per-IP в секундах: записи без активных соединений удаляются фоновой
    /// очисткой. 0 — записи живут до перезапуска.
    /// </summary>
    public int TtlSeconds { get; set; } = 1800;

    /// <summary>
    /// Верхняя граница числа отслеживаемых адресов в реестре per-IP статистики. Новые адреса
    /// сверх предела не учитываются (растёт <c>peerTrackingOverflow</c>) — защита от сканирования.
    /// </summary>
    public int MaxPeers { get; set; } = 100_000;
}