namespace TgWsProxy.Domain;

/// <summary>
/// Настройки записи лога в файл (вложенный блок <c>logs</c>). Все ключи блока — «только старт»:
/// конвейер Serilog собирается один раз при запуске процесса и на лету не перенастраивается.
/// </summary>
public sealed class LogsConfig
{
    /// <summary>
    /// Путь к файлу лога с ротацией. Пусто — только консоль.
    /// Инициализируется пустой строкой по той же причине, что и прежний плоский <c>logPath</c>:
    /// иначе <c>GET /api/config</c> отдавал бы значение <c>null</c>, а <c>PUT /api/config</c>
    /// видел бы ложное изменение «null → ""» и требовал перезапуск (F-2.11).
    /// </summary>
    public string Path { get; set; } = "";

    /// <summary>
    /// При записи в файл: лимит размера одного файла в МБ перед ротацией (минимум 32 КБ).
    /// 0 — ротация по часам вместо ограничения размера.
    /// </summary>
    public double MaxMegabytes { get; set; } = 5;

    /// <summary>
    /// Число архивных лог-файлов при ротации (минимум 1 — ротация без бэкапа не ограничивает размер).
    /// </summary>
    public int RetainedFileCount { get; set; } = 1;
}